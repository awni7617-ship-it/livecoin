#!/usr/bin/env node
/**
 * Build a single-file version of the whole app.
 *
 *   npm run bundle   ->   dist/forecourt-worker.js
 *
 * Everything ends up in one file: the Worker, and the front end inlined as
 * strings instead of the assets binding. That file can be pasted straight into
 * the Cloudflare dashboard's Worker editor, so the app can be deployed with no
 * terminal, no Git and nothing installed — bind a D1 database as DB and it runs.
 *
 * The normal `npm run deploy` path does not use this; it serves public/ from
 * Cloudflare's edge, which is faster and cheaper.
 */

import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist');
mkdirSync(out, { recursive: true });

const asset = (file) => JSON.stringify(readFileSync(join(root, 'public', file), 'utf8'));

const shim = `
import worker from './src/index.js';

const ASSETS = {
  '/': { body: ${asset('index.html')}, type: 'text/html; charset=utf-8' },
  '/app.js': { body: ${asset('app.js')}, type: 'text/javascript; charset=utf-8' },
  '/styles.css': { body: ${asset('styles.css')}, type: 'text/css; charset=utf-8' },
};

// Stand in for the assets binding so the Worker code itself is unchanged.
const assetsBinding = {
  async fetch(request) {
    const path = new URL(request.url).pathname;
    const file = ASSETS[path] || ASSETS[path.replace(/\\/index\\.html$/, '/')] || ASSETS['/'];
    return new Response(file.body, {
      headers: {
        'content-type': file.type,
        'cache-control': path === '/' ? 'no-cache' : 'public, max-age=3600',
      },
    });
  },
};

export default {
  fetch(request, env, ctx) {
    return worker.fetch(request, { ...env, ASSETS: env.ASSETS || assetsBinding }, ctx);
  },
};
`;

const entry = join(root, '.bundle-entry.mjs');
writeFileSync(entry, shim);

const banner = `// Forecourt — single-file build. Paste into the Cloudflare dashboard Worker
// editor, deploy, then add a D1 database binding named DB. Nothing else needed.
// Source: the forecourt/ folder (src/*.js + public/*). Do not edit this file by
// hand — run \`npm run bundle\` again instead.
`;

await build({
  entryPoints: [entry],
  outfile: join(out, 'forecourt-worker.js'),
  bundle: true,
  format: 'esm',
  target: 'es2022',
  platform: 'neutral',
  charset: 'utf8',
  legalComments: 'none',
  banner: { js: banner },
});

const { rmSync, statSync } = await import('node:fs');
rmSync(entry);
const size = statSync(join(out, 'forecourt-worker.js')).size;
process.stdout.write(`\n  dist/forecourt-worker.js  ${(size / 1024).toFixed(0)} KB\n\n`);
